namespace StrategyCore
{
    /// <summary>
    /// Приёмник юнита — приём ЛЕЧЕНИЯ (шаг 3 схемы «пакет и приёмник», §12).
    ///
    /// Здесь принимается РЕШЕНИЕ: какую величину лечения юнит получит на самом деле. Само здоровье
    /// приёмник не трогает — исполнение остаётся в <c>Unit.ChangeHP</c>, как на шаге 1 у контроля
    /// (там решение в приёмнике, а тело в <c>Unit.StunApply</c> и соседях). Граница та же: приёмник
    /// решает, юнит исполняет.
    ///
    /// Отдельный файл — правило 22: новая фича кладётся партиалом, <c>UnitReceiver.cs</c> не раздувается.
    ///
    /// Множитель берётся из состояний, висящих на юните (<c>unit.effectors</c>). Своего реестра и
    /// своего таймера у лечения нет и быть не должно: жизненный цикл наложений уже написан
    /// (<c>Effector.EffectorUpdate</c> — истечение, <c>EffectorRemove</c> — досрочное снятие), а второй
    /// механизм того же назначения нарушил бы правила 1 и 5.
    ///
    /// Метод чистый и детерминированный: ни бросков случайности, ни записи состояния. Один и тот же
    /// список наложений на сервере и на клиенте даёт один и тот же ответ.
    ///
    /// Клиентского запрета здесь НЕТ и на этом шаге быть не должно: <c>ChangeHP</c> сегодня считается
    /// на любом пире, как и на шагах 0–2.
    /// </summary>
    public partial class UnitReceiver
    {
        /// <summary>
        /// Принять пакет лечения. Возвращает величину ПОСЛЕ множителя получаемого лечения —
        /// с ней <c>Unit.ChangeHP</c> продолжает так же, как продолжал с исходной.
        ///
        /// Правило подсчёта (решение Artsiom 29.08.2026): среди наложений с ВКЛЮЧЁННЫМ множителем —
        /// если есть значения меньше 1, действует НАИМЕНЬШЕЕ из них (усиления при этом игнорируются
        /// целиком); иначе, если есть значения больше 1, действует НАИБОЛЬШЕЕ; иначе множитель 1.
        /// Перемножения нет: ослабление всегда главнее усиления, а два одинаковых ослабления
        /// не складываются в более сильное.
        ///
        /// Силой наложения (<c>EffectorHolder.powerMultiplier</c>) множитель НЕ масштабируется —
        /// берётся ровно то число, что записано в ассете состояния (решение Artsiom 29.08.2026).
        /// </summary>
        public float Receive(in HealPacket p)
        {
            // Наименьшее ослабление и наибольшее усиление ищутся за ОДИН проход. Обе переменные стартуют
            // с 1: если ослаблений не встретилось, weakest так и останется 1 и ветка ниже не сработает —
            // отдельные флаги «нашлось ли» не нужны. Юнит без состояний проходит цикл за ноль итераций
            // и получает свою величину нетронутой — это и есть короткий путь для подавляющего
            // большинства вызовов (регенерация каждого юнита каждые 0,1 с).
            float weakest = 1f;
            float strongest = 1f;

            for (int i = 0; i < unit.effectors.Count; i++)
            {
                Effector effector = unit.effectors[i].effector;
                if (!effector.healReceivedMultiplierOn) continue;

                float multiplier = effector.healReceivedMultiplier;

                // Отрицательный множитель зажимается в ноль (решение Artsiom 30.08.2026). Без зажима
                // лечение стало бы ВЫЧИТАНИЕМ здоровья мимо брони, типа урона, щитов и реакций,
                // причём ChangeHP при обнулении здоровья не убивает — юнит остался бы ходячим с нулём
                // и регенился обратно (ту же ловушку чинили в SkillBuff.cs:153). Ноль пропускается
                // как есть и означает «лечение не проходит».
                // ВНИМАНИЕ: правило валидатора, которое пометило бы такую настройку ошибкой, отложено
                // (решение Artsiom 30.08.2026) — подсказки в редакторе нет, зажим молчаливый.
                if (multiplier < 0f) multiplier = 0f;

                if (multiplier < weakest) weakest = multiplier;
                else if (multiplier > strongest) strongest = multiplier;
            }

            // Ослабление главнее: пока есть хоть одно значение меньше 1, усиления не смотрим вовсе.
            if (weakest < 1f) return p.amount * weakest;
            if (strongest > 1f) return p.amount * strongest;

            return p.amount;
        }
    }
}

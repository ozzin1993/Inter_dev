using UnityEngine;

namespace StrategyCore
{
    /// <summary>
    /// Развёртывание оружия перед стрельбой: юнит открывает огонь не сразу, а после неподвижной
    /// подготовки. Сдвинулся с места — подготовка начинается заново. Доворот на цель подготовку
    /// НЕ сбрасывает: он позицию не меняет, а порог сдвига считается только по горизонтали,
    /// поэтому спуск и подъём по рельефу тоже безопасны.
    ///
    /// Вся логика подготовки живёт здесь (правило 22). Наружу торчит ровно один метод —
    /// <see cref="ReadyToFire"/>: цикл атаки спрашивает «можно ли стрелять» и, пока ответ «нет»,
    /// стоит на месте и атаку не начинает.
    ///
    /// Серверная логика (правило 6): подготовку считает только сервер. Клиент про подготовку
    /// узнаёт не отсюда, а по значку состояния, который приёмник рассылает при наложении
    /// <see cref="deploymentVisual"/>.
    ///
    /// Значок снимается ДОСРОЧНО — когда подготовка закончилась или сорвалась. С 13.09.2026 приёмник
    /// отдаёт держатель наложения (его пробрасывает <c>Effector.EffectorAdd</c>), компонент держит его
    /// в поле и снимает ИМЕННО своё наложение. Искать наложение в общем списке unit.effectors
    /// по ссылке на ассет по-прежнему нельзя — там лежат наложения всех источников и обеих команд,
    /// и снялось бы чужое. Длительность наложения равна времени подготовки и остаётся СТРАХОВКОЙ:
    /// если снятие почему-то не случилось, значок истечёт сам.
    /// </summary>
    public class WeaponDeployment : MonoBehaviour
    {
        [Header("Развёртывание оружия")]
        [Tooltip("Сколько секунд юнит разворачивается, прежде чем сможет стрелять. " +
                 "0 — без подготовки, выстрел сразу. [БАЛАНС]")]
        [Min(0f)]
        [SerializeField] private float seconds = 1.75f;

        [Tooltip("Состояние-значок подготовки (значок и/или визуальный эффект). Накладывается на время " +
                 "подготовки и снимается, когда подготовка закончилась или сорвалась. Ассет должен быть " +
                 "НЕ бессрочным и с категорией «Нет», иначе длительность подготовки к нему не применится.")]
        [SerializeField] private Effector deploymentVisual;

        [Tooltip("Насколько юнит должен сдвинуться по горизонтали за одну проверку, чтобы подготовка " +
                 "сбросилась, в метрах. Мелкая толкотня соседями подготовку ломать не должна.")]
        [Min(0f)]
        [SerializeField] private float moveResetDistance = 0.01f;

        // Юнит-носитель. Кэшируется в Awake; без него подготовка никогда не завершится.
        private Unit unit;

        // Позиция на прошлой проверке сдвига.
        private Vector3 lastPosition;

        // Подготовка начата (отсчёт идёт) / подготовка закончена (стрелять можно).
        private bool preparing;
        private bool ready;

        // Момент времени, когда подготовка заканчивается.
        private float finishAt;

        // Держатель наложенного значка подготовки — то, что вернул приёмник. Держим, чтобы снять
        // досрочно ИМЕННО своё наложение. null — значка от этого компонента на юните нет.
        private EffectorHolder deploymentHolder;

        void Awake()
        {
            unit = GetComponent<Unit>();
            lastPosition = transform.position;
            if (unit != null) unit.OnDie += OnUnitDeath;
        }

        void OnDestroy()
        {
            if (unit != null) unit.OnDie -= OnUnitDeath;
        }

        void OnDisable()
        {
            ResetPreparation();
        }

        // Сигнатура под Unit.OnDie: кто умер, игрок-убийца, юнит-убийца, начисляются ли награды.
        void OnUnitDeath(Unit unitThatDies, int playerKiller, Unit unitKiller, bool rewards)
        {
            ResetPreparation();
        }

        void Update()
        {
            // Правило 6: подготовку считает только сервер.
            if (NetworkConnectionHandler.isClient) return;

            // Компонент Unit ядро снимает с трупа — на мёртвом и на «ничьём» объекте подготовки нет.
            if (unit == null || unit.dead) { ResetPreparation(); return; }

            if (MovedSinceLastCheck()) ResetPreparation();
        }

        /// <summary>
        /// Готов ли юнит открыть огонь. true — стрелять можно, false — ещё разворачивается.
        /// Зовётся циклом атаки каждый кадр, пока цель на дистанции атаки.
        /// </summary>
        public bool ReadyToFire()
        {
            // Правило 6: клиент атаку не гейтит — подготовку считает сервер, клиент видит её значком.
            if (NetworkConnectionHandler.isClient) return true;

            // Мёртвый не стреляет никогда.
            if (unit == null || unit.dead) { ResetPreparation(); return false; }

            // Вторая проверка сдвига в том же кадре: ловит перемещение, случившееся между Update
            // и вызовом из цикла атаки.
            if (MovedSinceLastCheck()) ResetPreparation();

            // Подготовка выключена настройкой либо уже отработала.
            if (seconds <= 0f || ready) return true;

            if (!preparing)
            {
                preparing = true;
                finishAt = Time.time + seconds;
                ShowDeploymentVisual();
            }

            // В кадре начала подготовки сюда попадаем всегда: finishAt заведомо больше текущего времени.
            if (Time.time < finishAt) return false;

            ready = true;

            // Подготовка закончилась — значок снимаем здесь же, в том же кадре. Иначе он доживал бы
            // остаток наложения: истечение считается на тике эффекторов (0,1 с), а готовность — по Time.time.
            HideDeploymentVisual();
            return true;
        }

        /// <summary>
        /// Сдвинулся ли юнит по горизонтали с прошлой проверки. Точку отсчёта двигает всегда:
        /// и Update, и <see cref="ReadyToFire"/> меряют сдвиг от одной и той же позиции.
        /// </summary>
        bool MovedSinceLastCheck()
        {
            Vector3 delta = transform.position - lastPosition;
            delta.y = 0f; // подъём и спуск по рельефу движением не считаем
            lastPosition = transform.position;

            // Сравнение квадратов — чтобы не считать корень каждый кадр.
            return delta.sqrMagnitude > moveResetDistance * moveResetDistance;
        }

        /// <summary>
        /// Повесить значок подготовки на время подготовки. Повторное наложение того же ассета той же
        /// силы и длительности приёмник не дублирует, а обнуляет отсчёт уже висящему наложению —
        /// поэтому перезапуск подготовки продлевает значок, а не плодит второй, и держатель приходит
        /// тот же самый.
        /// </summary>
        void ShowDeploymentVisual()
        {
            if (deploymentVisual == null) return;

            // Источник наложения — сам юнит. Длительность равна времени подготовки — это страховка,
            // а не рабочий путь: значок снимает HideDeploymentVisual (см. описание класса).
            deploymentHolder = Effector.EffectorAdd(unit, deploymentVisual, unit, unit.owner, durationOverride: seconds);
        }

        /// <summary>
        /// Снять значок подготовки досрочно. Снимается РОВНО тот держатель, что отдал приёмник при
        /// наложении; остальные наложения того же ассета в <c>unit.effectors</c> не задеваются —
        /// именно за этим и завёден возврат держателя.
        ///
        /// Оговорка по владению: приёмник слипает наложения одной КОМАНДЫ с теми же силой и длительностью
        /// в один держатель (<c>UnitReceiver.Statuses.cs</c>), источник при слипании не сверяется. Если тот же
        /// ассет с той же длительностью успеет наложить союзник, держатель окажется общим и снятие уберёт
        /// и его наложение. Для значка подготовки это умозрительно (ассет служебный, длительность — своя
        /// настройка юнита), но в контракте это есть.
        ///
        /// Поиск по списку — один на срыв подготовки, а не на кадр: держатель тут же забывается,
        /// и повторный заход выходит первой строкой. Проверка «ещё числится у юнита» нужна потому,
        /// что наложение могло истечь само (та самая страховка длительностью): снимать истёкшее нельзя —
        /// <c>EffectorRemove</c> второй раз снял бы пассивные эффекты и второй раз послал клиентам
        /// «значок убрать».
        ///
        /// Клиента здесь не бывает: держатель появляется только в <see cref="ShowDeploymentVisual"/>,
        /// а тот живёт за серверным гейтом <see cref="ReadyToFire"/> — у клиента поле всегда <c>null</c>.
        /// </summary>
        void HideDeploymentVisual()
        {
            if (deploymentHolder == null) return;

            if (unit != null && unit.effectors.Contains(deploymentHolder))
                Effector.EffectorRemove(unit, deploymentHolder);

            deploymentHolder = null;
        }

        /// <summary>
        /// Сбросить подготовку: следующий запрос готовности начнёт отсчёт заново. Значок снимаем здесь же —
        /// срыв подготовки (сдвиг с места, смерть, выключение компонента) не должен оставлять на юните
        /// «идёт развёртывание» на остаток длительности.
        /// </summary>
        void ResetPreparation()
        {
            preparing = false;
            ready = false;

            HideDeploymentVisual();
        }
    }
}

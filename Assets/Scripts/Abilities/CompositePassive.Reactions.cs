    // ============ КОНСТРУКТОР ПАССИВКИ: ОСЬ «РЕАКЦИИ» (правило 22 — партиал по фиче) ==
    // Ось «когда сработало», независимая от оси «свойства». Четыре события боя, у каждого свой набор
    // полей (решение Artsiom 2026-08-17). Каждое поле — тонкая обёртка над УЖЕ СУЩЕСТВУЮЩИМ механизмом
    // (правило 2): точка «входящий урон до брони» и точка «урон получен» живут в InterflowCombat,
    // смерть и добивание — в хабе смертей MatchManager.DeathEvents, падение здоровья — штатное
    // событие Unit.OnHPChange. Правок ядра ассета ни одно из четырёх не требует.
    //
    // Эти четыре блока ЗАМЕНЯЮТ собой пять классов (решение Artsiom 2026-08-17 «заменять сразу»):
    // Evasion, FlatDamageBlock, Counterattack (реакция «носителя ударили»), DeathEffects («погиб»),
    // OnKillCryPassive («кого-то убил»). Классы и их ассеты сносятся отдельным шагом после миграции.
    //
    // ЭТОТ ФАЙЛ — ТОЛЬКО ДАННЫЕ. Подписка на события и исполнение идут следующим шагом.

    /// <summary>Реакция 1. Носителя ударили: уход от удара, снижение урона и ответный удар.</summary>
    [Serializable]
    public class PassiveOnDamagedBlock
    {
        [Tooltip("Включить блок: носитель как-то отвечает на полученный удар — уходит от него, гасит его или бьёт в ответ.")]
        public bool enabled;

        // ---------------------------------------------------------------- УСЛОВИЯ --

        [Tooltip("Реагировать только на удары оружием. ВЫКЛ — блок сработает и на урон способностей, зон и состояний. " +
                 "ВАЖНО: у урона не от удара бьющий часто неизвестен, и ответный удар в этом случае бьёт по кругу вслепую.")]
        public bool onlyDirectAttack = true;

        [Tooltip("Тип урона, на который блок реагирует. Пусто — на любой.")]
        public DamageType onlyDamageType;

        [Tooltip("Реагировать только на удары СПЕРЕДИ. ВЫКЛ — с любой стороны. " +
                 "Направление считается от позиции бьющего к тому, куда смотрит носитель; " +
                 "если бьющий неизвестен, удар считается пришедшим НЕ спереди.")]
        public bool onlyFromFront;

        [Tooltip("Полный угол сектора «спереди» в градусах: 90 — это по 45 градусов влево и вправо от взгляда. " +
                 "Работает только при включённом «только спереди».")]
        [Range(0f, 360f)]
        public float frontAngle = 90f;

        // ------------------------------------------------------------ УХОД ОТ УДАРА --

        [Tooltip("Шанс полностью уйти от удара, по уровням: 0 — никогда, 1 — всегда. " +
                 "Сработал — урона нет вообще, снижение и ответный удар уже не считаются. Бросок делает только сервер.")]
        public float[] evadeChance;

        // ------------------------------------------------------------ СНИЖЕНИЕ УРОНА --

        [Tooltip("Множитель входящего урона по уровням: 0.8 — минус двадцать процентов, 1 — не менять. " +
                 "Считается ДО брони. Пусто или 0 — блок множителя выключен.")]
        public float[] incomingMultiplier;

        [Tooltip("Сколько единиц вычесть из удара, по уровням. Считается ПОСЛЕ множителя. 0 — не вычитать.")]
        public float[] flatBlock;

        [Tooltip("Нижняя граница урона после вычета: удар не может стать слабее этого числа. " +
                 "Обычно 1 — чтобы удар нельзя было обнулить совсем.")]
        public float minDamage = 1f;

        [Tooltip("Доля ТЕКУЩЕГО здоровья, ниже которой вычет удваивается. 0 — удвоения нет.")]
        [Range(0f, 1f)]
        public float doubleBlockBelowHp;

        // ------------------------------------------------------------- ОТВЕТНЫЙ УДАР --

        [Tooltip("Включить ответный удар: получив урон, носитель бьёт по кругу вокруг себя.")]
        public bool counterEnabled;

        [Tooltip("Урон ответа как доля от урона собственной атаки носителя, по уровням. 0.5 — половина обычного удара.")]
        public float[] counterPercentOfAttack;

        [Tooltip("Добавка к ответу числом, по уровням. Складывается с долей выше. 0 — только доля.")]
        public float[] counterFlatDamage;

        [Tooltip("Тип урона ответа. Пусто — берётся тип атаки носителя.")]
        public DamageType counterDamageType;

        [Tooltip("Радиус ответного удара вокруг носителя, метры, по уровням.")]
        public float[] counterRadius;

        [Tooltip("Максимум задетых ответом за один раз. 0 — без ограничения.")]
        [Min(0)]
        public int counterMaxTargets;

        [Tooltip("Кого задевает ответный удар (обычно враг + юнит + земля/вода/воздух).")]
        public UnitSelector counterSelector;

        [Tooltip("Состояния, накладываемые задетым ответом (например замедление). Пусто — только урон.")]
        public Effector[] counterEffectors;

        [Tooltip("Откат ответного удара в секундах: чаще этого носитель в ответ не бьёт. 0 — отвечать на каждый удар.")]
        public float counterCooldown = 1f;

        [Tooltip("Ответный удар ТОЛЬКО при сработавшем уходе от удара — связка «отразил → ударил в ответ». " +
                 "Требует ненулевого шанса ухода выше, иначе ответ не сработает никогда. " +
                 "В этом режиме ответ бьёт по самому бьющему (если он известен, жив и в радиусе ответа), а не по кругу. " +
                 "ВЫКЛ — ответ идёт на любой полученный удар, как раньше.")]
        public bool counterOnlyOnEvade;
    }

    /// <summary>Реакция 2. Носитель погиб: что происходит в месте его гибели.</summary>
    [Serializable]
    public class PassiveOnDeathBlock
    {
        [Tooltip("Включить блок: в месте гибели носителя что-то происходит. " +
                 "Условие «нужна технология» отдельным полем не задаётся — открытием умения уже управляют " +
                 "требуемая технология и требуемый уровень самого умения.")]
        public bool enabled;

        [Tooltip("Радиус урона и лечения вокруг места гибели, метры, по уровням.")]
        public float[] radius;

        [Tooltip("Урон врагам в радиусе, по уровням. 0 — не бить.")]
        public float[] enemyDamage;

        [Tooltip("Тип урона по врагам. Обязателен, если урон больше нуля.")]
        public DamageType enemyDamageType;

        [Tooltip("Кого считать врагом (обычно враг + юнит + земля/вода/воздух).")]
        public UnitSelector enemySelector;

        [Tooltip("Лечение союзникам числом, по уровням. 0 — не лечить числом.")]
        public float[] allyHealFlat;

        [Tooltip("Лечение союзникам долей от ИХ максимального здоровья, по уровням. 0.25 — четверть максимума цели. " +
                 "Складывается с лечением числом.")]
        public float[] allyHealPercentOfMaxHp;

        [Tooltip("Лечить только ОДНОГО ближайшего союзника. ВЫКЛ — лечить всех в радиусе.")]
        public bool healOnlyNearest;

        [Tooltip("Кого считать союзником (обычно свой и союзник + юнит + земля/вода/воздух).")]
        public UnitSelector allySelector;

        [Tooltip("Заготовка горящего пятна (нужен компонент GroundDamageZone), которое останется в месте гибели. " +
                 "Пусто — пятна нет. Владельцем становится владелец носителя.")]
        public GameObject zonePrefab;

        [Tooltip("Заготовка юнита, призываемого в месте гибели. Пусто — никого не призывать.")]
        public Unit summonPrefab;

        [Tooltip("Сколько юнитов призвать.")]
        [Min(0)]
        public int summonCount = 1;

        [Tooltip("Сколько секунд живут призванные. 0 — постоянные.")]
        public float summonLifetime;

        [Tooltip("Призванные слушают общие приказы Атака и Защита.")]
        public bool summonObeyCommands = true;

        [Tooltip("Приказ призванным, если общие приказы они НЕ слушают.")]
        public BottomTableAction summonCommand = BottomTableAction.Attack;

        [Tooltip("Разброс точек появления, метры. Имеет смысл при количестве больше одного.")]
        public float summonSpawnSpread = 1f;
    }

    /// <summary>Реакция 3. Носитель кого-то убил.</summary>
    [Serializable]
    public class PassiveOnKillBlock
    {
        [Tooltip("Включить блок: добив врага, носитель что-то получает сам или даёт союзникам вокруг.")]
        public bool enabled;

        [Tooltip("Состояния союзникам в радиусе (клич). Пусто — союзникам ничего.")]
        public Effector[] cryEffectors;

        [Tooltip("Радиус клича вокруг добившего, метры, по уровням.")]
        public float[] cryRadius;

        [Tooltip("Кого считать союзником для клича (обычно свой и союзник + юнит + земля/вода/воздух).")]
        public UnitSelector crySelector;

        [Tooltip("Накладывать клич и на самого добившего.")]
        public bool includeSelf;

        [Tooltip("Лечение добившему числом, по уровням. 0 — не лечить числом.")]
        public float[] killerHealFlat;

        [Tooltip("Лечение добившему долей от ЕГО максимального здоровья, по уровням. 0.15 — пятнадцать процентов максимума. " +
                 "Складывается с лечением числом.")]
        public float[] killerHealPercentOfMaxHp;
    }

    /// <summary>Реакция 4. Здоровье носителя упало ниже доли.</summary>
    [Serializable]
    public class PassiveOnHpBelowBlock
    {
        [Tooltip("Включить блок: когда здоровье носителя падает ниже порога, что-то происходит один раз.")]
        public bool enabled;

        [Tooltip("Доля здоровья, при пересечении которой ВНИЗ блок срабатывает. 0.3 — при падении ниже тридцати процентов. " +
                 "Повторно сработает только после того, как здоровье поднимется выше порога.")]
        [Range(0f, 1f)]
        public float threshold = 0.3f;

        [Tooltip("Состояния самому носителю. Пусто — себе ничего.")]
        public Effector[] selfEffectors;

        [Tooltip("Состояния союзникам вокруг носителя. Пусто — союзникам ничего.")]
        public Effector[] allyEffectors;

        [Tooltip("Радиус раздачи состояний союзникам, метры, по уровням.")]
        public float[] allyRadius;

        [Tooltip("Кого считать союзником (обычно свой и союзник + юнит + земля/вода/воздух).")]
        public UnitSelector allySelector;

        [Tooltip("Откат в секундах: чаще этого блок не сработает, даже если здоровье снова пересечёт порог. " +
                 "0 — откат не нужен, хватает возврата здоровья выше порога.")]
        public float cooldown;
    }


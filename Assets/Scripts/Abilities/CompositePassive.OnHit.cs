    // ==== КОНСТРУКТОР ПАССИВКИ: ОСЬ «РЕАКЦИИ», СОБЫТИЕ 5 (правило 22 — партиал по фиче) ====
    // «Носитель попал по цели» — пятое событие оси реакций. Отдельным партиалом, а не добавкой
    // в CompositePassive.Reactions.cs: там уже 235 строк на четыре события, и этот блок один
    // весит больше любого из них (правило 22 — не наращивать файл вширь).
    //
    // Точка подключения — штатный список атакующего Unit.OnAfterDamageDealCallbacks. Он копируется
    // в снаряд, поэтому событие покрывает и дальнобойных. Регистрация идемпотентная, через готовые
    // InterflowAbility.CallbackAdd / CallbackRemove по паре (умение, уровень). Правок ядра ассета
    // не требуется (правило 2).
    //
    // Этот блок ЗАМЕНЯЕТ собой узкие классы, живущие ровно на этом событии: ApplyVulnerabilityOnHit,
    // BonusDamageVsUnitType, BonusDamageVsCondition, PiercingLine, EveryNthAttack, LifestealPassive,
    // EffectorSpread и шанс оглушения Basher. Классы и их ассеты сносятся отдельным шагом после
    // сверки по числам; существующие ассеты этой сессией НЕ мигрируются (решение 4 плана).
    //
    // Про уровни: числа блока — СКАЛЯРЫ, не списки по уровням (решение Artsiom 2026-08-27:
    // у обычных умений уровень один; уровни остаются только у умений героя и решаются отдельно).
    // Этим блок отличается от четырёх соседних блоков реакций, где числа записаны массивами.
    //
    // ЭТОТ ФАЙЛ — ТОЛЬКО ДАННЫЕ. Подписка на событие и исполнение — следующим шагом,
    // в CompositePassive.OnHitRuntime.cs.

    /// <summary>Реакция 5. Носитель попал по цели: условия срабатывания и что происходит.</summary>
    [Serializable]
    public class PassiveOnHitBlock
    {
        /// <summary>Состояние цели, при котором блок вообще срабатывает.</summary>
        public enum TargetCondition
        {
            [InspectorName("Без условия")]                    Any,
            [InspectorName("У цели НЕТ поглощающего щита")]   NoAbsorbShield,
            [InspectorName("У цели ЕСТЬ поглощающий щит")]    HasAbsorbShield,
            [InspectorName("Цель оглушена")]                  Stunned,
            [InspectorName("Цель ранена ниже порога ХП")]     BelowHpFraction
        }

        [Tooltip("Включить блок: когда носитель наносит урон цели, что-то происходит дополнительно.")]
        public bool enabled;

        // ---------------------------------------------------------------- УСЛОВИЯ --

        [Tooltip("Только прямой удар оружием. ВЫКЛ — блок сработает и от урона способностей, зон и состояний носителя. " +
                 "ВАЖНО: сплеш и добавочный урон приходят сюда с признаком «не прямая атака», поэтому при " +
                 "выключенной галке счётчик «каждый N-й» считает и их.")]
        public bool onlyDirectAttack = true;

        [Tooltip("Срабатывать каждый N-й удар: 3 — на каждом третьем. 0 или 1 — на каждом. " +
                 "Счётчик ведётся отдельно по каждому носителю и НЕ сбрасывается при улучшении технологии.")]
        [Min(0)]
        public int everyNthHit;

        [Tooltip("Шанс срабатывания: 1 — всегда, 0.3 — тридцать процентов, 0 — никогда. Бросок делает только сервер. " +
                 "Считается ПОСЛЕ счётчика «каждый N-й»: не сработавший бросок счёт не возвращает.")]
        [Range(0f, 1f)]
        public float chance = 1f;

        [Tooltip("Собственный откат блока в секундах: чаще этого блок у одного носителя не сработает. 0 — без отката.")]
        public float cooldown;

        [Tooltip("Типы цели, по которым блок работает (Unit — юниты, Building — здания и башни, " +
                 "StaticDestructible, Tree, Item). Пусто — по любой цели.")]
        public UnitType[] onlyTargetTypes;

        [Tooltip("Боевые роли цели, по которым блок работает. Пусто — по любой роли.")]
        public Unit.UnitCategory[] onlyTargetCategories;

        [Tooltip("Состояние цели, при котором блок работает.")]
        public TargetCondition onlyTargetCondition = TargetCondition.Any;

        [Tooltip("Порог доли ХП для условия «ранена ниже порога». 0.5 — ниже половины здоровья.")]
        [Range(0f, 1f)]
        public float conditionHpFraction = 0.5f;

        [Tooltip("Тип урона, которым нанесён удар, — только на него блок реагирует. Пусто — на любой.")]
        public DamageType onlyDamageType;

        // ------------------------------------------------------------ ДОБАВОЧНЫЙ УРОН --

        [Tooltip("Добавочный урон как доля от только что нанесённого удара, . " +
                 "1 — ещё столько же (итого двойной удар), 0.25 — плюс четверть. 0 — без добавки. " +
                 "Добавка проходит ту же броню и ту же матрицу типов, что и основной удар.")]
        public float extraDamageMultiplier;

        [Tooltip("Добавочный урон числом. Складывается с долей выше. 0 — только доля.")]
        public float extraDamageFlat;

        [Tooltip("Тип добавочного урона. Пусто — тип нанесённого удара.")]
        public DamageType extraDamageType;

        // ------------------------------------------------------------ СОСТОЯНИЯ НА ЦЕЛЬ --

        [Tooltip("Состояния, накладываемые на цель попадания. Пусто — цели ничего.")]
        public Effector[] targetEffectors;

        // ----------------------------------------------------------------- УЯЗВИМОСТЬ --

        [Tooltip("Множитель входящего урона на цели: 1.4 — цель получает на 40% больше. " +
                 "1 — уязвимость не вешается.")]
        public float vulnerabilityMultiplier = 1f;

        [Tooltip("Сколько секунд держится уязвимость. 0 — уязвимость не вешается.")]
        public float vulnerabilityDuration;

        [Tooltip("Тип урона, к которому применяется уязвимость (например «зажигательный»). Пусто — к любому.")]
        public DamageType vulnerabilityOnlyDamageType;

        [Tooltip("Уязвимость действует только на прямые атаки по цели. ВЫКЛ — и на урон способностей и зон.")]
        public bool vulnerabilityOnlyDirectIncoming;

        // ------------------------------------------------------------------ ВАМПИРИЗМ --

        [Tooltip("Доля нанесённого урона, возвращаемая носителю в здоровье. 0.1 — десять процентов. " +
                 "Считается от урона ДО брони цели — так это работало у прежнего вампиризма, семантика сохранена.")]
        public float healFromDamagePercent;

        // ------------------------------------------------------- ПЕРЕНОС НА СОСЕДЕЙ --

        [Tooltip("Шанс перенести состояния на соседа поражённой цели. 0 — переноса нет.")]
        [Range(0f, 1f)]
        public float spreadChance;

        [Tooltip("Радиус вокруг ПОРАЖЁННОЙ ЦЕЛИ, в котором ищется сосед, метры.")]
        public float spreadRadius;

        [Tooltip("Сколько соседей задевает перенос. 1 — только ближайший.")]
        [Min(1)]
        public int spreadNeighbourCount = 1;

        [Tooltip("Переносить состояния АТАКИ носителя — те, что реально были наложены на цель. " +
                 "ВЫКЛ — переносить только список ниже.")]
        public bool spreadAttackEffectors = true;

        [Tooltip("Дополнительные состояния соседу. Пусто — только состояния атаки.")]
        public Effector[] spreadExtraEffectors;

        [Tooltip("Кого считать соседом для переноса (обычно враг + юнит + земля/вода/воздух).")]
        public UnitSelector spreadSelector;

        // ------------------------------------------------------- ОГЛУШЕНИЕ И ОТБРОС --

        [Tooltip("Оглушить цель на столько секунд. 0 — не оглушать. " +
                 "Штатное оглушение само уважает иммунитет к контролю.")]
        public float stunSeconds;

        [Tooltip("Отбросить цель от носителя на столько метров. 0 — не отбрасывать.")]
        public float knockbackDistance;

        [Tooltip("Заморозка цели на миг отброса, секунды. 0 — без заморозки.")]
        public float knockbackStunSeconds;

        [Tooltip("Отброс уважает иммунитет к контролю. Заморозку штатное оглушение гейтит само в любом случае.")]
        public bool knockbackRespectControlImmunity = true;

        // ------------------------------------------------------------ ЗАДЕТЬ ПО ЛИНИИ --

        [Tooltip("Ширина коридора поражения в метрах: задеты те, чей центр ближе половины этой ширины к линии удара. " +
                 "0 — по линии не бить.")]
        public float lineWidth;

        [Tooltip("На сколько метров коридор продолжается ЗА основную цель. 0 — только до неё.")]
        public float lineExtraDistance;

        [Tooltip("Урон задетым по линии как доля от урона основного удара. 1 — столько же, 0.5 — половина.")]
        public float lineDamagePercent = 1f;

        [Tooltip("Максимум дополнительно задетых по линии. 0 — без ограничения.")]
        [Min(0)]
        public int lineMaxTargets;

        [Tooltip("Накладывать задетым по линии состояния атаки носителя, как основной цели.")]
        public bool lineApplyAttackEffectors = true;

        [Tooltip("Кого задевает коридор (обычно враг + юнит + земля/вода/воздух).")]
        public UnitSelector lineSelector;

        // ------------------------------------------------------------ КЛИЧ СОЮЗНИКАМ --

        [Tooltip("Состояния союзникам вокруг носителя (клич). Пусто — союзникам ничего.")]
        public Effector[] cryEffectors;

        [Tooltip("Радиус клича вокруг носителя, метры.")]
        public float cryRadius;

        [Tooltip("Минимальный тир союзника (поле tier на юните). Ниже — клич не получают.")]
        public int cryMinAllyTier = 1;

        [Tooltip("Максимальный тир союзника. Например 1–2 — только младшие юниты.")]
        public int cryMaxAllyTier = 6;

        [Tooltip("Накладывать клич и на самого носителя.")]
        public bool cryIncludeSelf;

        [Tooltip("Кого считать союзником для клича (обычно свой и союзник + юнит + земля/вода/воздух).")]
        public UnitSelector crySelector;

        // ---------------------------------------------------------- ГЛУБОКАЯ РАНА --

        [Tooltip("Вешать на цель «глубокую рану»: цель получает урон, пока двигается. Стоя на месте — не кровоточит.")]
        public bool bleedEnabled;

        [Tooltip("Урон раны за каждый пройденный целью метр.")]
        public float bleedDamagePerMeter = 2f;

        [Tooltip("Сколько секунд держится рана.")]
        public float bleedDuration = 4f;

        [Tooltip("Тип урона раны. Пусто — тип нанесённого удара.")]
        public DamageType bleedDamageType;
    }

    public partial class CompositePassive

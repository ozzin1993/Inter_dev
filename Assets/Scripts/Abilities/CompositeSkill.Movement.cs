    // Три блока: рывок ЦЕЛИ к кастеру, ОТБРАСЫВАНИЕ целей от кастера и перемещение САМОГО КАСТЕРА
    // в точку приложения. Все идут через общий хелпер Knockback (правило 2: перемещение по NavMesh
    // уже реализовано там, им же пользуется усиленная атака EveryNthAttack).

    /// <summary>2. Рывок цели вплотную к кастеру.</summary>
    [System.Serializable]
    public class SkillPullBlock
    {
        [Tooltip("Включить блок: цель мгновенно перемещается вплотную к кастеру.")]
        public bool enabled;

        [Tooltip("Зазор между габаритами кастера и цели, метры. 0 — впритык. " +
                 "Габариты берутся у NavMeshAgent обоих, поэтому цель не окажется внутри кастера.")]
        public float gap;
    }

    /// <summary>18. Перемещение кастера в точку приложения (телепорт, рывок, прыжок).</summary>
    [System.Serializable]
    public class SkillCasterMoveBlock
    {
        [Tooltip("Включить блок: кастер переносится в точку приложения умения. " +
                 "Точку задаёт режим цели: «умный выбор точки» — выбранное место, «умный выбор юнита» — позиция цели. " +
                 "Блок идёт ПЕРВЫМ, до всех блоков по целям: отброс считается уже от точки приземления, " +
                 "а рывок цели к кастеру — к новому месту кастера.")]
        public bool enabled;

        [Tooltip("Уважать иммунитет к контролю у самого кастера. " +
                 "ВЫКЛ — кастер перемещается даже под иммунитетом (это его собственное умение, а не контроль извне).")]
        public bool respectControlImmunity;

        // [Interflow 2026-09-18, решения Artsiom 47 и 48] Время и дуга — ТОЛЬКО ПОКАЗ. Геймплейно кастер
        // оказывается в конечной точке СРАЗУ (сервер переносит его синхронизированным входом хелпера),
        // а полёт за travelSeconds рисует клиент по факту события. Серверной корутины перемещения нет:
        // расхождение «удар придёт, пока модель ещё в пути» принято решением 47.
        [Tooltip("Сколько секунд КЛИЕНТ ведёт модель кастера из старой точки в новую. 0 — мгновенный телепорт. " +
                 "ВАЖНО: на игру время не влияет — геймплейно кастер оказывается в конечной точке сразу, " +
                 "и все блоки умения считаются уже от неё. Это длительность ПОКАЗА полёта.")]
        [Min(0f)]
        public float travelSeconds;

        [Tooltip("Высота дуги прыжка в середине полёта, метры. 0 — рывок по земле без подъёма. " +
                 "Работает только вместе со временем полёта выше. Дугу рисует клиент; она видна, " +
                 "пока клиент не считает юнита движущимся — отданная в полёте команда движения её оборвёт.")]
        [Min(0f)]
        public float leapHeight;

        [Tooltip("Насколько метров ПРОЛЕТЕТЬ ЗА точку приложения по направлению движения. " +
                 "0 — встать ровно в точку. Нужно «рывку сквозь строй»: цель в точке приложения остаётся за спиной. " +
                 "Фактическая точка садится на навигационную сетку, как и обычная: нет места — кастер встанет ближе.")]
        [Min(0f)]
        public float passThroughDistance;

        [Tooltip("Визуал события «кастер начал перемещение»: играется в точке, ОТКУДА он стартовал. " +
                 "Носитель — кастер. Сюда же кладётся стейт анимации полёта. Пусто — без визуала.")]
        public EventPresentation startPresentation = new EventPresentation();

        [Tooltip("Визуал события «кастер прибыл»: играется в точке приземления. Носитель — кастер. " +
                 "При заданном времени полёта показ ждёт конца полёта. Пусто — без визуала.")]
        public EventPresentation arrivePresentation = new EventPresentation();
    }

    /// <summary>15. Отбрасывание целей от кастера.</summary>
    [System.Serializable]
    public class SkillKnockbackBlock
    {
        [Tooltip("Включить блок: цели отлетают от кастера.")]
        public bool enabled;

        [Tooltip("На сколько метров отбросить, по уровням. Отсчёт идёт от кастера через цель: " +
                 "цель улетает по прямой прочь от него.")]
        public float[] distance;

        [Tooltip("Оглушение отброшенных, секунды, по уровням. 0 — не оглушать. " +
                 "Штатное оглушение само уважает иммунитет к контролю.")]
        public float[] stunSeconds;

        [Tooltip("Уважать иммунитет к контролю у целей. ВКЛ — юнит с иммунитетом остаётся на месте. " +
                 "ВЫКЛ — отбрасывает всех, кто вообще может двигаться.")]
        public bool respectControlImmunity = true;

        // [Interflow 2026-09-18, решения Artsiom 49 и 50] Как и у блока 18, время — только показ:
        // цель переставляется в конечную точку СРАЗУ. Но в отличие от кастера, на это время она
        // помечается служебным состоянием «в полёте» — иначе она атаковала бы и кастовала из точки,
        // где её модель ещё не стоит.
        [Tooltip("Сколько секунд КЛИЕНТ ведёт модель цели из старой точки в новую. 0 — мгновенный отброс. " +
                 "Геймплейно цель оказывается в конечной точке сразу; на это время на неё вешается " +
                 "служебное состояние «в полёте»: активных действий она не совершает, а повторный отброс " +
                 "пока оно держится — пропускается. Состояние идёт мимо сопротивлений и иммунитета к контролю.")]
        [Min(0f)]
        public float travelSeconds;

        [Tooltip("Визуал события «цель отброшена»: играется НА КАЖДОЙ отброшенной цели. " +
                 "Носитель И точка — САМА цель, точка — её позиция ДО отброса. Пусто — без визуала.")]
        public EventPresentation presentation = new EventPresentation();
    }

    public partial class CompositeSkill
    {
        /// <summary>
        /// Рывок цели к кастеру. Возвращает false, если цель не сдвинулась: иммунитет к контролю,
        /// неподвижный юнит или здание, нет валидной точки на NavMesh.
        ///
        /// Решение Artsiom 2026-08-06: несостоявшийся рывок ОТСЕКАЕТ цель от остальных блоков этого каста —
        /// умение считается исполненным (откат и мана списаны штатно), но по этой цели не делает ничего.
        /// </summary>
        bool ApplyPull(Unit castingUnit, Unit target)
        {
            if (pull == null || !pull.enabled) return true;   // блок выключен — цель обрабатываем как обычно
            if (castingUnit == null || target == null) return false;

            Vector3 point = Knockback.PointNextTo(castingUnit, target, pull.gap);

            return Knockback.MoveTo(target, point, true);     // иммунитет к контролю спасает от рывка
        }

        /// <summary>
        /// Отбрасывание цели от кастера. Идёт ПОСЛЕДНИМ по каждой цели: все блоки до него считают
        /// расстояния от исходной позиции цели (вторичные цели вокруг неё, зона, визуал попадания),
        /// и сдвинь мы её раньше — они бы работали от новой точки.
        ///
        /// Неудача (иммунитет, неподвижная цель, нет валидной точки на NavMesh) молча пропускается:
        /// в отличие от рывка к кастеру, отброс не отсекает цель — урон и состояния ей уже достались.
        ///
        /// [Interflow 2026-09-18, решения Artsiom 49–52] Направление осталось радиальным «от кастера
        /// через цель» (решение 52 — поля «по взгляду» нет), своего отбора у блока нет (решение 51 —
        /// отброс достаётся всем, кого задело умение). Новое здесь только время показа: цель уезжает
        /// в конечную точку СРАЗУ, а на travelSeconds получает служебное состояние «в полёте» и факт
        /// события, по которому клиент рисует полёт её модели.
        /// </summary>
        void ApplyKnockback(Unit castingUnit, int level, Unit target)
        {
            if (knockback == null || !knockback.enabled) return;
            if (castingUnit == null || target == null) return;

            float distance = LevelValue(knockback.distance, level);
            float stun = LevelValue(knockback.stunSeconds, level);
            if (distance <= 0f && stun <= 0f) return;

            // Повторный отброс летящей цели ПРОПУСКАЕТСЯ целиком (решение Artsiom 50): второй отброс
            // за время полёта увёл бы цель из точки, к которой клиент уже ведёт её модель, и показ
            // разошёлся бы с игрой. Флаг производный, его выставляет пересчёт по списку состояний.
            if (target.inFlight) return;

            // Точка ДО отброса: она уезжает клиенту фактом события — с экрана её брать нельзя,
            // снимок позиции и факт события идут разными сообщениями, порядок не гарантирован.
            Vector3 from = target.transform.position;

            bool moved = Knockback.Apply(target, castingUnit.transform.position, distance, stun,
                                         knockback.respectControlImmunity, castingUnit, castingUnit.owner);

            // Не сдвинулась (иммунитет, неподвижная, нет места на сетке) — ни состояния, ни показа полёта:
            // вести модель некуда, она стоит там же.
            if (!moved) return;

            if (knockback.travelSeconds > 0f)
                target.InFlightStart(knockback.travelSeconds, castingUnit, castingUnit.owner);

            // Носитель И точка — сама цель (решение Artsiom 57): точка — та, ОТКУДА она полетела.
            // Куда лететь, клиент берёт из её сетевой позиции — сервер уже переставил цель.
            EmitEventPresentation(this, (int)AbilityEventCode.SkillKnockbackTarget, knockback.presentation,
                                  target, level, target, from);
        }

        /// <summary>
        /// Перемещение кастера. Идёт ПЕРВЫМ в применении блоков (решение Artsiom 48): у обоих рывков
        /// Саши удар и отброс считаются уже от точки приземления. Набор целей от переноса не меняется —
        /// цели набраны раньше (CompositeSkill.Cast.cs), — меняются направление отброса и точка рывка
        /// цели к кастеру.
        ///
        /// Перенос МГНОВЕННЫЙ и синхронизированный (решение 47): точка садится на навигационную сетку,
        /// обновляются клетка сетки и клетка тумана, позиция уезжает клиентам прямым каналом.
        /// Полёт за travelSeconds рисует только клиент — серверной корутины перемещения нет.
        /// Неудача (нет точки на сетке, кастер неподвижен, иммунитет) молча пропускается.
        /// </summary>
        /// <param name="start">Точка, ОТКУДА кастер стартовал. Нужна шлейфу (блок 17) и клиенту.</param>
        /// <param name="landing">Точка приземления. При неудаче — там же, где кастер и стоял.</param>
        /// <returns>true — кастер ФАКТИЧЕСКИ перенесён; шлейф выкладывается только в этом случае.</returns>
        bool ApplyCasterMove(Unit castingUnit, int level, Vector3 point, out Vector3 start, out Vector3 landing)
        {
            start = castingUnit != null ? castingUnit.transform.position : point;
            landing = start;

            if (casterMove == null || !casterMove.enabled) return false;
            if (castingUnit == null) return false;

            // Пролёт за точку приложения (решение Artsiom 47, поле passThroughDistance): направление
            // считается от старой позиции кастера к точке приложения. Посадку на сетку делает хелпер.
            Vector3 destination = Knockback.PointBeyond(start, point, castingUnit.transform.forward,
                                                        casterMove.passThroughDistance);

            if (!Knockback.MoveTo(castingUnit, destination, casterMove.respectControlImmunity)) return false;

            // Фактическая точка приземления — та, куда хелпер посадил юнита на сетке, а не желаемая.
            landing = castingUnit.transform.position;

            // Старт: носитель — кастер, точка — ОТКУДА он полетел. Из этого факта клиент берёт начало
            // полёта; конец — сетевая позиция кастера, которую прямой канал уже везёт.
            EmitEventPresentation(this, (int)AbilityEventCode.SkillCasterMoveStart, casterMove.startPresentation,
                                  castingUnit, level, castingUnit, start);

            // Прибытие: сервер признаёт его сразу (перенос мгновенный). При заданном времени полёта
            // клиент откладывает ПОКАЗ этого набора до конца полёта — сервер про это не знает и знать
            // не должен (правило 6).
            EmitEventPresentation(this, (int)AbilityEventCode.SkillCasterMoveArrive, casterMove.arrivePresentation,
                                  castingUnit, level, castingUnit, landing);

            return true;
        }
    }

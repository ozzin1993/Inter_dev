namespace StrategyCore
{
    /// <summary>
    /// Пакет лечения — описание одного применяемого лечения, адресованное юниту.
    /// Разбирает его приёмник <see cref="UnitReceiver"/> (схема «пакет и приёмник», §1, §3).
    ///
    /// Шаг 3 схемы: поле РОВНО одно — величина. Больше в пакете быть не должно, потому что больше
    /// сегодня и не известно: воронкой лечения служит <c>Unit.ChangeHP</c>, а она принимает только
    /// число. Ни источника лечения, ни умения, ни игрока-лекаря в этот вызов не приходит — завести
    /// такие поля значило бы придумать данные, которых нет (правило 7). Понадобится источник —
    /// поле появится тогда же, когда его начнут передавать вызывающие.
    ///
    /// Почему struct: образцы — <see cref="DamagePacket"/>, <see cref="ControlPacket"/>,
    /// <see cref="EffectorPacket"/>. Лечение рождается в самом горячем пути, какой есть у юнита:
    /// регенерация тикает у КАЖДОГО живого юнита каждые 0,1 с (<c>Unit.Ability.cs:356</c>), а сверх
    /// неё идут лечение умением, вампиризм и лечение во времени. Значимый тип не даёт выделения
    /// в куче на каждый тик (руководство Unity, programming best practices).
    /// Это данные времени исполнения, в Inspector они не живут — <c>[SerializeField]</c> не нужен.
    /// </summary>
    public struct HealPacket
    {
        /// <summary>Величина лечения до множителя (то же, что положительный параметр <c>amount</c> у <c>ChangeHP</c>).</summary>
        public float amount;

        /// <summary>Собрать пакет из одной записи лечения.</summary>
        public HealPacket(float amount)
        {
            this.amount = amount;
        }
    }
}

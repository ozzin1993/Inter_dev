namespace StrategyCore
{
    /// <summary>
    /// [Interflow fix 2026-09-09 hit-outcome] ИСХОД ПРИЁМА УДАРА — «состоялся ли удар по цели».
    ///
    /// Пакет <see cref="DamagePacket"/> — это ВХОД применения: что и от кого адресовано юниту.
    /// Исход — ВЫХОД приёмника, поэтому он едет отдельным значением, а не полем пакета.
    /// До этой правки сигнала о промахе в конструкции не было вовсе: <c>UnitReceiver.Receive</c>
    /// возвращает «погиб ли юнит», и проигранный бросок «удар не достиг цели» отдавал то же
    /// <c>false</c>, что и успешный приём. Из-за этого бьющий вешал реакции попадания и бил
    /// разлётом даже по промаху (дефект F14).
    ///
    /// ВАЖНО: «принят» и «снято больше нуля» — РАЗНЫЕ вещи. У принятого удара ноль снятого
    /// здоровья штатен: щит съел удар целиком, таблица «тип брони × тип урона» дала ноль,
    /// правило входящего обнулило урон (см. <c>Units/UnitReceiver.cs</c>, комментарий к числу урона).
    /// Поэтому проверять исход через «урон больше нуля» нельзя.
    ///
    /// По сети не ходит: значения нужны только внутри одного серверного вызова.
    /// </summary>
    public enum DamageOutcome
    {
        /// <summary>Исход неизвестен: пакет отложен в очередь реакций и будет разобран позже,
        /// либо приёмник отработал у клиента (он ничего не считает). Реакции бьющего по такому
        /// исходу НЕ запускаются — «неизвестно» не читается как «принят».</summary>
        Unknown = 0,

        /// <summary>Удар принят: цель прошла бросок «удар не достиг цели» и не была неуязвима.
        /// Сюда же попадает удар, полностью поглощённый щитом или обнулённый бронёй и таблицей
        /// типов (решение Artsiom 09.09.2026: щит реакции попадания не отбивает).</summary>
        Accepted = 1,

        /// <summary>Удар не принят: проигран бросок «удар не достиг цели» (промах бьющего от
        /// ослепления или уход жертвы), отбой неуязвимостью, либо цель уже мертва.</summary>
        Rejected = 2
    }
}

namespace StrategyCore
{
    /// <summary>
    /// Вид контроля — что именно применяется к юниту.
    /// Имена совпадают с воронками <c>Unit.Stun</c> / <c>Unit.Mute</c> / <c>Unit.Disarm</c>,
    /// чтобы по значению сразу читалось, какой исполнитель будет вызван.
    /// Отброс и рывок сюда НЕ входят: у них своя геометрия и свой исполнитель
    /// (<see cref="Knockback"/>), в приёмник они заходят только вопросом об иммунитете.
    /// </summary>
    public enum ControlType
    {
        /// <summary>Оглушение: юнит заморожен и ничего не делает, пока стан не истечёт.</summary>
        Stun,

        /// <summary>Немота: юнит не может применять умения.</summary>
        Mute,

        /// <summary>Обезоруживание: юнит не может атаковать.</summary>
        Disarm,
    }

    /// <summary>
    /// Пакет контроля — описание одного применяемого контроля, адресованное юниту.
    /// Разбирает его приёмник <see cref="UnitReceiver"/> (схема «пакет и приёмник», §1, §3).
    ///
    /// Шаг 1 схемы: пакет несёт РОВНО то, что сегодня принимают воронки контроля, — вид и время.
    /// Ни одного нового поля здесь нет и быть не должно: переезд идёт отдельно от смены баланса
    /// (§12 схемы). Единственная принятая смена поведения этого шага — иммунитет к контролю
    /// теперь проверяется для всех трёх видов, — живёт в приёмнике, а не в пакете.
    ///
    /// Почему struct: образец — <see cref="DamagePacket"/>. Контроль рождается не только на каст,
    /// но и в реакциях, зонах и снарядах, то есть в бою на каждом попадании. Значимый тип не даёт
    /// выделения в куче на каждый вызов (руководство Unity, programming best practices).
    /// Это данные времени исполнения, в Inspector они не живут — <c>[SerializeField]</c> не нужен.
    /// </summary>
    public struct ControlPacket
    {
        /// <summary>Вид контроля — по нему приёмник выбирает проверки и исполнителя.</summary>
        public ControlType type;

        /// <summary>Длительность в секундах (то же, что параметр <c>time</c> у воронок контроля).</summary>
        public float time;

        /// <summary>Собрать пакет из вида контроля и его длительности.</summary>
        public ControlPacket(ControlType type, float time)
        {
            this.type = type;
            this.time = time;
        }
    }
}

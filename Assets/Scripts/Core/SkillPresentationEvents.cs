using System;
using UnityEngine;

namespace StrategyCore
{
    /// <summary>
    /// [Interflow 2026-08-06] Хаб событий ПРЕЗЕНТАЦИИ УМЕНИЙ. Решение Artsiom: событийная инверсия —
    /// сетевой слой и симуляция про презентацию не знают ничего и лишь поднимают здесь событие-ФАКТ.
    /// Рисует единственный подписчик — клиентский презентер (SkillPresenter, сборка Interflow.Client).
    ///
    /// Зависимость односторонняя и держится границей сборок, а не дисциплиной: Interflow.Client ссылается
    /// на Interflow.Game, обратной ссылки нет. На выделенном сервере клиентской сборки нет вовсе —
    /// подписчиков ноль, Invoke уходит в никуда, кода презентации в билде нет.
    ///
    /// Прецедент событийного хаба в проекте — MatchManager.DeathEvents (OnUnitDeathServer).
    /// ВАЖНО: события статические — подписчик обязан отписываться (OnDisable/OnDestroy),
    /// иначе останется висячий обработчик уничтоженного объекта.
    /// </summary>
    public static class SkillPresentationEvents
    {
        // ============================== СРАБАТЫВАНИЕ УМЕНИЯ ==============================
        // ОДНО событие на любое срабатывание: автокаст, каст с кнопки, «умный выбор», прок пассивки.
        // Особых случаев нет (решение Artsiom 2026-08-06: отдельное SkillProc отменено — после перевода
        // пассивок в конструктор их прок и есть срабатывание умения, два сообщения описывали бы один факт).

        /// <summary>
        /// Умение сработало: (кастер, id умения, уровень, цель наведения, точка приложения).
        /// Кастер и цель могут быть null — умение без кастера или без конкретной цели.
        /// </summary>
        public static event Action<Unit, int, int, Unit, Vector3> SkillFired;

        /// <summary>Поднять факт «умение сработало». Зовётся сервером (локально) и приёмником RPC (у клиента).</summary>
        public static void RaiseSkillFired(Unit caster, int abilityID, int level, Unit aimUnit, Vector3 aimPoint)
            => SkillFired?.Invoke(caster, abilityID, level, aimUnit, aimPoint);

        // ============================== ЖИЗНЬ ЮНИТА ==============================
        // Нужны презентеру, чтобы заводить и снимать постоянный круг радиуса (ауры).
        // Серверное MatchManager.OnUnitSpawned для этого не годится: клиенту оно не приходит,
        // а юниты у него появляются репликацией, загрузкой сцены и данными сохранения.

        /// <summary>
        /// Юнит полностью инициализирован на ЭТОМ пире: умения приведены в рабочее состояние,
        /// уровни и блокировки проставлены. Раньше этого момента читать умения юнита нельзя.
        /// </summary>
        public static event Action<Unit> UnitReady;

        /// <summary>Юнит убран с этого пира (снятие netID). Зеркало UnitReady.</summary>
        public static event Action<Unit> UnitGone;

        /// <summary>Поднять факт «юнит готов». Зовётся в конце инициализации юнита.</summary>
        public static void RaiseUnitReady(Unit unit) => UnitReady?.Invoke(unit);

        /// <summary>Поднять факт «юнит убран». Зовётся при снятии netID.</summary>
        public static void RaiseUnitGone(Unit unit) => UnitGone?.Invoke(unit);

        // ============================== ЗАМАХ ==============================
        // Начало и конец замаха. Нужны, чтобы область действия появлялась ДО срабатывания.
        // Своих сообщений для этого не заводим: факт поднимается рядом с ОТПРАВКОЙ штатного сообщения
        // (для хоста) и в его ПРИЁМНИКЕ (для клиента) — сообщение идёт SendTo.NotServer и до хоста не доходит.

        /// <summary>Юнит начал каст: (кастер, id умения, цель, точка). Цель и точка могут быть пустыми.</summary>
        public static event Action<Unit, int, Unit, Vector3> CastStarted;

        /// <summary>Каст юнита прерван или завершён ядром: (кастер).</summary>
        public static event Action<Unit> CastStopped;

        /// <summary>Поднять факт «каст начался». Зовётся приёмником сообщения о начале каста.</summary>
        public static void RaiseCastStarted(Unit caster, int abilityID, Unit targetUnit, Vector3 targetPoint)
            => CastStarted?.Invoke(caster, abilityID, targetUnit, targetPoint);

        /// <summary>Поднять факт «каст прерван». Зовётся приёмником сообщения о прерывании.</summary>
        public static void RaiseCastStopped(Unit caster) => CastStopped?.Invoke(caster);

        // ============================== ПОГЛОЩАЮЩИЙ ЩИТ ==============================
        // Величина щита живёт на сервере (AbsorbShield); факт нужен клиентскому сегменту
        // на полоске здоровья (ShieldBarDisplay, сборка Interflow.Client).

        /// <summary>Объём поглощающего щита юнита изменился: (носитель, объём; 0 — щит снят).</summary>
        public static event Action<Unit, float> ShieldChanged;

        /// <summary>Поднять факт «щит изменился». Зовётся сервером (локально) и приёмником RPC (у клиента).</summary>
        public static void RaiseShieldChanged(Unit unit, float amount)
            => ShieldChanged?.Invoke(unit, amount);

        // ============================== РАЗОВЫЙ ФАКТ БОЯ ==============================
        // ОДНО событие на все шесть случаев §15 схемы (решения Artsiom Р1–Р7 от 07.09.2026): удар не достиг
        // цели, щит поглотил, неуязвим, состояние отбито иммунитетом, состояние отбито сопротивлением,
        // нанесён урон. Приёмник поднимает только ФАКТ и ПРИЧИНУ: про надписи, слова и цвета боевой код
        // не знает ничего (решение Р6), их выбирает клиентский презентер по настройкам.
        // Путь тот же, что у щита: подъём на сервере локально + своё сообщение сети клиентам.

        // [Interflow 2026-09-10] К числу факта добавлена ПАРА «было → стало»: по одному числу нельзя
        // проверить баланс — «Снижен 6» не говорит, из скольки. Оба нуля означают «пары нет».

        /// <summary>
        /// По юниту произошло разовое событие боя: (юнит, причина, число).
        /// Число осмысленно только у части причин (см. <see cref="BattleFactReason"/>); у остальных 0.
        /// </summary>
        public static event Action<BattleFactInfo> BattleFact;

        /// <summary>Поднять разовый факт боя. Зовётся сервером (локально) и приёмником сообщения (у клиента).</summary>
        /// <param name="info">Полное описание факта: что, по кому, от кого и в рамках какого удара.</param>
        public static void RaiseBattleFact(in BattleFactInfo info) => BattleFact?.Invoke(info);

        // ============================== РАЗБОР ЗАПИСИ УРОНА ==============================
        // [Interflow 2026-09-11] Решение Artsiom: детали удара едут ОДНИМ сводным сообщением на запись
        // урона, а не отдельными причинами факта. Причина — по одному итоговому числу не видно, из чего
        // оно сложилось: заявленное, правила жертвы, подписки (щит), броня с таблицей типов.
        // Тем же типом приезжает СВЁРНУТАЯ периодика: горение, аура и зона копятся на сервере
        // и отдают одну строку за интервал, а не строку на каждый тик.

        /// <summary>Разобрана одна запись урона (или пришла свёртка периодического источника).</summary>
        public static event Action<DamageStepInfo> DamageStep;

        /// <summary>Поднять разбор записи урона. Зовётся сервером (локально) и приёмником сообщения (у клиента).</summary>
        public static void RaiseDamageStep(in DamageStepInfo info) => DamageStep?.Invoke(info);

        // ============================== ФАКТ БЕЗ ЮНИТА ==============================
        // [Interflow 2026-09-09 passive-facts] Тот же разовый факт, но привязанный к ТОЧКЕ, а не к юниту.
        // Нужен ровно для случая, когда носителя уже нет: реакция «носитель погиб» срабатывает в месте
        // гибели, а к этому моменту netID носителя снят с учёта и сообщение «про юнита» уйти не может
        // (CanSendAbout → StillRegistered). Отдельное событие, а не null-юнит в предыдущем: подписчику
        // нужна позиция, и проверять «юнит null, значит смотри в другое поле» — лишняя развилка.

        /// <summary>Разовое событие боя в ТОЧКЕ мира: (позиция, причина, число).</summary>
        public static event Action<BattleFactInfo> BattleFactAt;

        /// <summary>Поднять разовый факт боя в точке. Зовётся сервером (локально) и приёмником сообщения.</summary>
        /// <param name="info">То же описание факта, но с пустым юнитом и заполненной точкой.</param>
        public static void RaiseBattleFactAt(in BattleFactInfo info) => BattleFactAt?.Invoke(info);

        // ============================== ЗОНЫ НА ЗЕМЛЕ ==============================

        /// <summary>
        /// Зона на земле появилась: (id зоны, id умения-источника, уровень, позиция, носитель).
        /// Носитель не null — «аура на время» (блок Б7): копию зоны презентер вешает на юнит, и она идёт за ним.
        /// </summary>
        public static event Action<int, int, int, Vector3, Unit> ZoneSpawned;

        /// <summary>Зона на земле закончила жизнь: (id зоны).</summary>
        public static event Action<int> ZoneDespawned;

        /// <summary>Поднять факт «зона появилась». Зовётся приёмником RPC (NetworkDataSync.UnitStatus).</summary>
        public static void RaiseZoneSpawned(int zoneId, int abilityID, int level, Vector3 position, Unit carrier)
            => ZoneSpawned?.Invoke(zoneId, abilityID, level, position, carrier);

        /// <summary>Поднять факт «зона исчезла». Зовётся приёмником RPC (NetworkDataSync.UnitStatus).</summary>
        public static void RaiseZoneDespawned(int zoneId)
            => ZoneDespawned?.Invoke(zoneId);
    }

    /// <summary>
    /// [Interflow 2026-09-11] Разовый факт боя ЦЕЛИКОМ: что произошло, по кому, от кого и в рамках какого
    /// удара. До этой правки те же данные ехали пятью параметрами события, и бьющего среди них не было —
    /// лента печатала только жертву. Номер удара, бьющий и умение добавлены решением Artsiom 11.09.2026:
    /// по номеру лента собирает строки одного удара в группу, по бьющему и умению печатает её заголовок.
    ///
    /// Структура, а не список параметров: полей стало девять, и подписчик читает их по именам.
    /// </summary>
    public struct BattleFactInfo
    {
        /// <summary>Юнит, с которым произошло событие. null — факт привязан к точке (носителя уже нет).</summary>
        public Unit unit;

        /// <summary>Точка мира. Осмысленна только когда <see cref="unit"/> пуст.</summary>
        public Vector3 position;

        /// <summary>Что именно произошло.</summary>
        public BattleFactReason reason;

        /// <summary>Число факта. Осмысленно только у части причин (см. <see cref="BattleFactReason"/>).</summary>
        public float value;

        /// <summary>Значение ДО события для скобки «было → стало». Оба нуля — скобки нет.</summary>
        public float before;

        /// <summary>Значение ПОСЛЕ события.</summary>
        public float after;

        /// <summary>Номер удара, внутри которого поднят факт. 0 — факт вне удара (выдача блока свойств,
        /// наложение состояния бафом): лента такую строку в группу не собирает.</summary>
        public int hitId;

        /// <summary>Бьющий или источник наложения. null — источника-юнита нет (состояние, зона, сейв).</summary>
        public Unit attacker;

        /// <summary>Умение-источник удара. −1 — умения нет: автоатака, урон в секунду состояния.</summary>
        public int abilityID;
    }

    /// <summary>
    /// [Interflow 2026-09-11] Разбор ОДНОЙ записи урона: что заявил бьющий и во что это превратилось
    /// на каждой ступени приёмника, плюс здоровье цели до и после. Решение Artsiom 11.09.2026 —
    /// детали удара едут сводным сообщением, а не россыпью причин.
    ///
    /// Этим же типом приезжает СВЁРНУТАЯ периодика (горение, аура, зона): у неё <see cref="ticks"/> больше
    /// нуля, <see cref="hitId"/> равен нулю, а ступени расчёта не заполняются — копить их по тикам
    /// бессмысленно, в свёртке осмысленны только сумма снятого и число тиков.
    /// </summary>
    public struct DamageStepInfo
    {
        /// <summary>Кому нанесён урон.</summary>
        public Unit victim;

        /// <summary>Кто нанёс. null — источник без юнита: зона на земле, отложенный урон.</summary>
        public Unit attacker;

        /// <summary>Умение-источник. −1 — умения нет (автоатака, урон в секунду состояния).</summary>
        public int abilityID;

        /// <summary>Номер удара — тот же, что у остальных фактов этого приёма пакета. 0 — свёртка периодики.</summary>
        public int hitId;

        /// <summary>Номер записи в пакете, с нуля, и сколько записей всего: умение бьёт несколькими сразу.</summary>
        public int recordIndex;

        /// <summary>Сколько записей урона в пакете.</summary>
        public int recordCount;

        /// <summary>Заявлено записью до всех расчётов.</summary>
        public float declared;

        /// <summary>После правил входящего урона жертвы (снижение, уязвимость).</summary>
        public float afterRules;

        /// <summary>После подписок: поглощающий щит и прочие снижения через колбэки.</summary>
        public float afterCallbacks;

        /// <summary>После брони и таблицы типов — столько ушло бы в здоровье без зажимов.</summary>
        public float afterArmor;

        /// <summary>Сколько здоровья снято на самом деле.</summary>
        public float dealt;

        /// <summary>Здоровье цели до этой записи.</summary>
        public float healthBefore;

        /// <summary>Здоровье цели после этой записи.</summary>
        public float healthAfter;

        /// <summary>Предельное здоровье цели — чтобы лента печатала «стало из максимума».</summary>
        public float healthMax;

        /// <summary>Сколько тиков свёрнуто в эту строку. 0 — разовый удар.</summary>
        public int ticks;

        /// <summary>Погибла ли цель от этой записи.</summary>
        public bool died;
    }

    /// <summary>
    /// Причина разового факта боя по юниту — шесть случаев набора Р1 (решение Artsiom 07.09.2026)
    /// плюс набор пассивных умений (2026-09-09). Объявлено здесь, а не отдельным файлом: вне события
    /// <see cref="SkillPresentationEvents.BattleFact"/> перечисление смысла не имеет (правило 5 —
    /// меньше точек входа).
    ///
    /// ВАЖНО: нумерация СПЛОШНАЯ от нуля, и по сети причина едет числом (см. отправку факта боя в
    /// <c>NetworkDataSync.UnitStatus.cs</c>). Порядок значений менять нельзя — только дописывать в конец,
    /// иначе сервер и клиент разойдутся в толковании номера.
    /// </summary>
    public enum BattleFactReason
    {
        /// <summary>Удар не достиг цели. Одна причина на промах бьющего и уход жертвы (решение Р4).</summary>
        HitMissed = 0,

        /// <summary>Поглощающий щит принял на себя часть или весь урон этого удара.</summary>
        ShieldAbsorbed = 1,

        /// <summary>Жертва неуязвима — урон отбит целиком.</summary>
        Invulnerable = 2,

        /// <summary>Наложение состояния отбито иммунитетом к контролю.</summary>
        StatusImmune = 3,

        /// <summary>Наложение состояния отбито сопротивлением 100 % и выше.</summary>
        StatusResisted = 4,

        /// <summary>По юниту прошёл урон. Величина — в числе факта.</summary>
        DamageDealt = 5,

        // ===== Пассивные умения: свойства и реакции (2026-09-09, для проверок) =====
        // Дописаны В КОНЕЦ: номера 0–5 уже разошлись по пирам, и сдвиг сломал бы толкование числа.

        /// <summary>Блок свойств пассивного умения выдан носителю. Число — номер блока, 1–8.</summary>
        PassiveBlockGranted = 6,

        /// <summary>Блок свойств пассивного умения снят с носителя. Число — номер блока, 1–8.</summary>
        PassiveBlockRevoked = 7,

        /// <summary>Сработал ответный удар по кругу (реакция 1). Число — урон одной цели.</summary>
        PassiveCounter = 8,

        /// <summary>Сработал встречный удар при уходе (реакция 1). Число — урон по бьющему.</summary>
        PassiveCounterOnEvade = 9,

        /// <summary>Сработала реакция «носитель погиб» (реакция 2). Число — задетых врагов. Факт идёт ТОЧКОЙ.</summary>
        PassiveDeathBurst = 10,

        /// <summary>Сработала реакция «носитель кого-то убил» (реакция 3). Число — задетых кличем союзников.</summary>
        PassiveOnKill = 11,

        /// <summary>Сработала реакция «здоровье ниже доли» (реакция 4). Число — доля здоровья в процентах.</summary>
        PassiveHpBelow = 12,

        /// <summary>
        /// Правило жертвы срезало часть входящего удара (множитель или вычет числом). Число — сколько
        /// единиц срезано. Название БЕЗ слова «пассивка» намеренно: то же правило заводят баф и щит
        /// умения, и приписывать надпись пассивке было бы неверно.
        /// </summary>
        IncomingDamageReduced = 13,

        // ===== Реакция 5 «носитель попал по цели» и пассивки, собранные кодом (2026-09-10) =====
        // Дописаны В КОНЕЦ по тому же правилу, что и набор 6–13: номера 0–13 уже разошлись по пирам,
        // и сдвиг сломал бы толкование числа.

        /// <summary>
        /// Сработал кирпич реакции «носитель попал по цели» (реакция 5 конструктора пассивки).
        /// Число — порядковый номер кирпича, 1–10; название клиент берёт из ассета настроек.
        /// </summary>
        PassiveOnHitBrick = 14,

        /// <summary>
        /// Сработала пассивка, собранная КОДОМ, а не конструктором (два десятка старых классов).
        /// Число — id умения: строку с названием клиент собирает сам, потому что канал факта
        /// везёт одно число и слова в нём не ездят.
        /// </summary>
        PassiveProc = 15,

        /// <summary>Пассивка, собранная кодом, выдана носителю. Число — id умения.</summary>
        PassiveGranted = 16,

        /// <summary>Пассивка, собранная кодом, снята с носителя. Число — id умения.</summary>
        PassiveRevoked = 17,

        // ===== Что видно в бою по числам (2026-09-10, проверка баланса) =====
        // Снижение входящего урона уже показывалось (13). Рост урона показан не был: считалось, что
        // его и так видно большим числом. Решение Artsiom 10.09.2026 — показывать и рост, иначе по
        // экрану не проверишь, сработала пассивка на усиление или нет.

        /// <summary>
        /// Модификаторы носителя увеличили ЕГО ИСХОДЯЩИЙ урон (ярость от нехватки здоровья, крит).
        /// Число — на сколько единиц вырос удар.
        /// </summary>
        OutgoingDamageIncreased = 18,

        /// <summary>
        /// Правило жертвы увеличило ВХОДЯЩИЙ урон (уязвимость). Число — на сколько единиц вырос удар.
        /// Зеркало <see cref="IncomingDamageReduced"/>.
        /// </summary>
        IncomingDamageIncreased = 19,

        /// <summary>
        /// На юнита НАЛОЖЕНО состояние (замедление, ускорение, броня и прочее). Число — id состояния:
        /// название клиент берёт из ассета состояния. Продление уже висящего состояния сюда НЕ идёт —
        /// иначе ауры залили бы ленту десятком строк в секунду.
        /// </summary>

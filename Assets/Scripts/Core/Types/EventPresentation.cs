using System;
using UnityEngine;

namespace StrategyCore
{
    /// <summary>
    /// [Interflow 2026-09-17, шаг 4 слияния] НАБОР ПОЛЕЙ РАЗОВОГО ВИЗУАЛА СОБЫТИЯ.
    ///
    /// Один и тот же набор лежит и у самого умения (его каст), и у каждого блока-хозяина,
    /// у которого есть своё событие: реакции пассивки, лечение умением, прилёт снаряда,
    /// удар с разгона, вампиризм. Проигрыватель у клиента ОДИН на все наборы
    /// (Client/SkillPresenter.PlayPresentation) — форм хранения больше не две.
    ///
    /// ПО СЕТИ СОДЕРЖИМОЕ НАБОРА НЕ ЕДЕТ, и это не выбор, а факт: <see cref="VFXReferencer"/>.id
    /// присваивается СЛУЧАЙНЫМ числом на каждом пире отдельно (Core/GameManager.cs:416-431) и только
    /// префабам из Resources/VFX, а у AudioClip идентификатора нет вовсе. По сети едет только АДРЕС
    /// набора — пара (id ассета-хозяина, код набора <see cref="AbilityEventCode"/>), а сам набор
    /// клиент берёт из своей копии ассета через Ability.PresentationFor(код).
    ///
    /// Длящегося в наборе нет: состояние-значок, копия снаряда и область сюда не входят
    /// (решение Artsiom 25 от 17.09.2026). Длящийся визуал — это эффектор через канал статусов.
    /// </summary>
    [Serializable]
    public class EventPresentation
    {
        [Tooltip("Имя стейта аниматора носителя, проигрываемого в момент события. Пусто — не проигрывать. " +
                 "Стейт заводится в контроллере юнита: строчными буквами, БЕЗ зацикливания и вне зарезервированных схем ядра " +
                 "(attack0…, death0…, idle0…, idleReady, cast, casting, hit, walk, building, construction) — иначе ядро спутает его со своими. " +
                 "Перебивает текущую анимацию, в том числе замах атаки.")]
        public string animationState = "";

        [Tooltip("Точка на модели носителя, из которой играет визуал у носителя (и вылетает снаряд умения). " +
                 "Точки настраиваются компонентом CharacterSockets на префабе. Нет компонента — берётся центр объекта.")]
        public SkillSocketType socket = SkillSocketType.RightHand;

        [Tooltip("Смещение от точки привязки в её собственных осях, метры. Например немного вперёд от ладони.")]
        public Vector3 localOffset;

        [Tooltip("Визуал У НОСИТЕЛЯ: играет из точки привязки. Пусто — без визуала.")]
        public VFXReferencer carrierVFX;

        [Tooltip("Через сколько секунд убрать визуал у носителя. Ноль или меньше — визуал не создаётся вовсе.")]
        public float carrierVfxLifetime = 2f;

        [Tooltip("Визуал В ТОЧКЕ события (место попадания, центр области, точка гибели). Пусто — без визуала.")]
        public VFXReferencer pointVFX;

        [Tooltip("Через сколько секунд убрать визуал в точке. Ноль или меньше — визуал не создаётся вовсе.")]
        public float pointVfxLifetime = 2f;

        [Tooltip("Звук у носителя. Пусто — без звука.")]
        public AudioClip carrierSound;

        [Tooltip("Звук в точке события. Пусто — без звука.")]
        public AudioClip pointSound;

        [Tooltip("Громкость звуков набора, 0..1.")]
        [Range(0f, 1f)]
        public float soundVolume = 1f;

        /// <summary>
        /// Задано ли в наборе хоть что-то, что можно показать. По нему сервер решает, слать ли факт:
        /// пустой набор сообщения не порождает (инвариант проекта §6).
        ///
        /// Числа (время жизни, громкость, точка привязки, смещение) сами по себе «заданностью» НЕ считаются:
        /// у них есть умолчания, и набор из одних умолчаний показывать нечего.
        /// </summary>
        public bool Any =>
            carrierVFX != null || pointVFX != null ||
            carrierSound != null || pointSound != null ||
            !string.IsNullOrEmpty(animationState);
    }

    /// <summary>
    /// Код НАБОРА у ассета-хозяина. Едет по сети ЧИСЛОМ внутри факта «умение сработало»
    /// (Core/SkillPresentationEvents.SkillFired), нового сообщения для набора нет — решение Artsiom 27
    /// от 17.09.2026, решение 06.08 «один факт на срабатывание» в силе.
    ///
    /// ИНВАРИАНТ: нумерация сплошная от нуля, значения ТОЛЬКО ДОПИСЫВАЮТСЯ В КОНЕЦ. Номера разошлись
    /// по всем пирам и лежат в сериализованном виде нигде, но по сети едут числом — перестановка
    /// значений разведёт сервер и клиента на разные наборы.
    /// </summary>
    public enum AbilityEventCode
    {
        /// <summary>0 — сработало САМО умение (каст). Сегодняшнее поведение до появления наборов.</summary>
        SkillCast = 0,
        /// <summary>Реакция 1 пассивки: носителя ударили (ответ по кругу и встречный при уходе).</summary>
        PassiveOnDamaged,
        /// <summary>Реакция 2 пассивки: носитель погиб — что происходит в месте гибели.</summary>
        PassiveDeath,
        /// <summary>Реакция 2 пассивки: гибель вылечила союзника (свой набор на каждого вылеченного).</summary>
        PassiveDeathHeal,
        /// <summary>Реакция 3 пассивки: носитель кого-то добил.</summary>
        PassiveKill,
        /// <summary>Реакция 4 пассивки: здоровье носителя упало ниже доли.</summary>
        PassiveHpBelow,
        /// <summary>Реакция 5 пассивки: носитель попал по цели (он же прилёт снаряда атаки).</summary>
        PassiveOnHit,
        /// <summary>Реакция 6 пассивки: носитель начал атаку. Показ ЛОКАЛЬНЫЙ на каждом пире, сообщения нет.</summary>
        PassiveAttackStart,
        /// <summary>Блок 7 умения: мгновенное лечение цели.</summary>
        SkillHeal,
        /// <summary>Блок 22 умения: снаряд этого умения прилетел.</summary>
        SkillProjectileImpact,
        /// <summary>Класс ChargeAttack: первый удар после разгона.</summary>
        ChargeImpact,
        /// <summary>Класс LifestealPassive: вампиризм вернул носителю здоровье.</summary>
        Lifesteal,
        /// <summary>
        /// Блок 14 умения, набор «ЦЕЛЬ»: попадание по ВТОРИЧНОЙ цели. Играет НА КАЖДОЙ задетой вторичной цели
        /// (решение Artsiom 31 от 17.09.2026), носитель И точка — САМА задетая цель, а не кастер
        /// (решение Artsiom 33 от 17.09.2026).
        /// </summary>
        SkillSecondaryHit,
        /// <summary>
        /// Блок 14 умения, набор «КАСТ»: сам заход блока вторичных целей. Играет ОДИН раз, ДО перебора
        /// целей; носитель — кастер, точка — позиция основной цели, вокруг которой идёт выборка
        /// (решение Artsiom 33 от 17.09.2026). От того, кого нашла выборка, не зависит.
        /// </summary>
        SkillSecondaryCast,
        /// <summary>
        /// Реакция 7 пассивки: погиб союзник. Играет НА НОСИТЕЛЕ, а не на погибшем: его netID к этому
        /// моменту уже снят с учёта (решение Artsiom 40 от 17.09.2026).
        /// </summary>
        PassiveAllyDeath,

        // [Interflow 2026-09-18, шаг 4 слияния, решение Artsiom 57] Пять кодов семьи «движение кастера,
        // отброс целей, облик». Дописаны В КОНЕЦ (числа 15–19), прежние не сдвинулись.
        // Три из пяти несут клиенту не только визуал, но и ПОВОД начать показ во времени
        // (полёт модели, подмену внешности) — своего сообщения ни у одного из них нет,
        // всё едет фактом «умение сработало» (решение 47).

        /// <summary>
        /// 15. Блок 18: кастер НАЧАЛ перемещение. Носитель — кастер, точка — ОТКУДА он стартовал
        /// (сервер к этому моменту уже перенёс его в конечную точку — решение Artsiom 47).
        /// По этому факту клиент ведёт модель кастера из точки события в его сетевую позицию
        /// за travelSeconds с подъёмом по leapHeight.
        /// </summary>
        SkillCasterMoveStart,
        /// <summary>
        /// 16. Блок 18: кастер ПРИБЫЛ. Носитель — кастер, точка — куда он прибыл. Сервером факт
        /// поднимается сразу (перенос мгновенный); при travelSeconds &gt; 0 показ набора клиент
        /// откладывает до конца полёта — это единственный набор семьи, чей момент показа
        /// определяет клиент, а не сервер.
        /// </summary>
        SkillCasterMoveArrive,
        /// <summary>
        /// 17. Блок 15: цель отброшена. Идёт НА КАЖДОЙ задетой цели (решение Artsiom 57): иначе клиент
        /// не знает, кого вести и откуда. Носитель И точка — САМА цель, точка — её позиция ДО отброса.
        /// </summary>
        SkillKnockbackTarget,
        /// <summary>
        /// 18. Блок 12: облик НАДЕТ. Носитель и точка — тот, кто сменил облик. По этому факту чистый
        /// клиент делает ТОЛЬКО подмену внешности (решение Artsiom 54): геймплейного полиморфа
        /// у клиента не появляется.
        /// </summary>
        SkillMorphOn,
        /// <summary>
        /// 19. Блок 12: облик СНЯТ. Парный к предыдущему (решение Artsiom 54): клиент возвращает
        /// исходную внешность. Потерянный факт оставит модель превращённой до конца матча — цена принята.
        /// </summary>
        SkillMorphOff,

        /// <summary>
        /// 20. Блок 11 пассивки: сработало РАССЕЧЕНИЕ (решение Artsiom 62 от 18.09.2026).
        /// ОДИН показ на срабатывание, а не на каждую задетую цель: у Халдора радиус 2,5 метра
        /// и набор на каждой цели стоил бы десятка сообщений на каждый его удар.
        /// Носитель — сам носитель умения; точка — цель удара, а при центре круга на носителе —
        /// сам носитель. Дописан В КОНЕЦ, прежние номера не сдвинулись.
        /// </summary>
        PassiveCleave
    }
}

namespace StrategyCore
{
    /// <summary>
    /// Служба сцены, которую поднимает <see cref="SceneStartup"/> в объявленном порядке.
    /// </summary>
    /// <remarks>
    /// Реализация ОБЯЗАНА быть идемпотентной: <see cref="Startup"/> вызывается дважды —
    /// стартовиком сцены (рано, в объявленном порядке) и собственным Awake службы
    /// (страховка для сцены, где стартовика нет). Второй вызов обязан ничего не делать.
    /// </remarks>
    public interface IStartupService
    {
        /// <summary>
        /// Поднять службу: опубликовать себя в своём Instance и выполнить инициализацию.
        /// </summary>
        void Startup();
    }
}

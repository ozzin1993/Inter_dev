using UnityEngine;

namespace StrategyCore
{
    // Маркер иммунитета к контролю. Пока Active — юнит не поддаётся контролю (стан; в будущем — заморозка/страх/чума).
    // Проверяется в Unit.Stun ([Interflow fix]) per-unit: иммунный пропускается, остальные станятся штатно.
    // Рефкаунт — чтобы несколько источников иммунитета (напр. Железный Приговор + будущий эффект) не гасили друг друга.
    // Наш компонент (Unit.cs не хранит состояние иммунитета). Ставят/снимают способности (напр. IronVerdictBuff).
    public class ControlImmunity : MonoBehaviour
    {
        int refs; // сколько активных источников иммунитета сейчас на юните

        // Иммунитет активен, пока есть хотя бы один источник.
        public bool Active => refs > 0;

        // Добавить источник иммунитета (баф вызывает при наложении).
        public void Add() => refs++;

        // Снять источник иммунитета (баф вызывает при снятии/истечении/смерти). Не уходит ниже нуля.
        public void Remove() { refs--; if (refs < 0) refs = 0; }
    }
}

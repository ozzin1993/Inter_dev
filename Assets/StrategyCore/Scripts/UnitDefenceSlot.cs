using UnityEngine;

namespace StrategyCore
{
    /// <summary>
    /// Слот юнита в строю защиты. Хранит ЛИНИЮ (приоритет) и индекс заполнения внутри неё. Поле слота
    /// в самом Unit вводить нельзя (правило 1) — поэтому отдельный наш компонент, который вешает MatchManager
    /// при спавне. Серверо-авторитетно: это рантайм-данные для позиционирования, по сети не синкаются
    /// (позиции едут штатным Unit.Move). Менеджер при смене активной точки/смерти пересчитывает позицию
    /// по тем же (priority, index), поэтому юнит переходит на «тот же» слот у другой сетки.
    /// </summary>
    public class UnitDefenceSlot : MonoBehaviour
    {
        [Tooltip("Линия (бэнд) в сетке = formationPriority юнита: 1 — передний ряд (к врагу), дальше — глубже.")]
        public int priority = 1;

        [Tooltip("Индекс заполнения внутри своей линии (0..). Меняется при компакции (смерть соседа).")]
        public int index = 0;
    }
}
